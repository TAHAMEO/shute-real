// ------------------------------------------------------------------ bolt-action helper

/** Round bolt action + bolt group (handle on the right). Origin of the bolt group on the bolt axis. */
function boltAction(b, L, o = {}) {
  const M = o.mat || 'blued';
  const r = o.r || 0.0165;
  b.tube(M, r, 0.000, L, { seg: b.q.seg });
  b.lathe(M, [[0, -0.004], [r - 0.003, -0.004], [r, 0.000]], { seg: b.q.seg });
  if (b.fp) {
    b.hole(M, r * 0.62, r * 0.78, o.portF ?? 0.105, 0.006, 0.0006, 0.060, { rz: -0.66 });
    b.hole(M, r * 0.95, 0.002, o.portF ?? 0.105, 0.0006, 0.014, 0.060);
  }
  const bolt = b.group('bolt', 0, 0, o.handleF ?? 0.030);
  bolt.tube('steel', 0.0095, -0.034, (o.portF ?? 0.105) + 0.025, { seg: b.q.segS, tint: 0.85 });
  bolt.lathe(M, [[0, -0.040], [0.0110, -0.040], [0.0135, -0.030], [0.0135, -0.012], [0.0098, -0.010]], { seg: b.q.segS });
  const hf = o.handleF ?? 0.030;
  bolt.box('steel', 0.020, -0.006, hf, 0.024, 0.006, 0.008, { rz: -0.55, tint: 0.85 });
  const knobR = o.knobR || 0.0085;
  bolt.sphere(o.knobMat || 'steel', 0.035, -0.016, hf + 0.004, knobR, { tint: o.knobMat ? 1 : 0.85, scale: [1, 1, 1.15] });
  return bolt;
}

